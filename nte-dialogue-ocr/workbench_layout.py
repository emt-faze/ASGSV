"""Shared live-workbench presentation for the two game adapters."""
from PySide6 import QtCore, QtWidgets as W


def build_live_dashboard(owner):
    layout = W.QVBoxLayout(owner)
    layout.setContentsMargins(0, 0, 0, 0)
    heading = W.QHBoxLayout()
    owner.description = W.QLabel('打开游戏，一键连接，切到其他窗口后仍持续识别。')
    owner.description.setWordWrap(True)
    heading.addWidget(owner.description, 1)
    owner.auto = W.QCheckBox('下次打开工具时自动连接')
    heading.addWidget(owner.auto)
    layout.addLayout(heading)

    actions = W.QHBoxLayout()
    owner.start = W.QPushButton('一键配置并开始')
    owner.start.setObjectName('primary')
    owner.start.setMinimumHeight(42)
    owner.stop = W.QPushButton('停止')
    owner.pause = W.QPushButton('暂停配音')
    owner.pause.setCheckable(True)
    owner.replay = W.QPushButton('重播本句')
    owner.skip = W.QPushButton('跳过本句')
    for button in (owner.start, owner.stop, owner.pause, owner.replay, owner.skip):
        actions.addWidget(button)
    for button in (owner.stop, owner.pause, owner.replay, owner.skip):
        button.setEnabled(False)
    actions.addStretch()
    owner.open_task = W.QPushButton('查看识别到的任务')
    owner.open_task.setEnabled(False)
    actions.addWidget(owner.open_task)
    layout.addLayout(actions)

    status_box = W.QGroupBox('当前工作状态')
    status_layout = W.QGridLayout(status_box)
    owner.state = W.QLabel('未启动 · 点击一键配置并开始')
    owner.state.setWordWrap(True)
    owner.state.setStyleSheet('font-size:16px;font-weight:700;color:#38bdf8;padding:4px;')
    status_layout.addWidget(owner.state, 0, 0, 1, 4)
    owner.capture_status = W.QLabel('尚未连接游戏')
    owner.ocr_status = W.QLabel('等待开始')
    owner.audio_status = W.QLabel('等待检查本地音频')
    owner.calibration_status = W.QLabel('按剧情和字幕编号匹配')
    for row, (left, value, right, other) in enumerate((
        ('游戏日志', owner.capture_status, '当前台词', owner.ocr_status),
        ('识别方式', owner.calibration_status, '声音播放', owner.audio_status)), 1):
        value.setWordWrap(True)
        other.setWordWrap(True)
        status_layout.addWidget(W.QLabel(left), row, 0)
        status_layout.addWidget(value, row, 1)
        status_layout.addWidget(W.QLabel(right), row, 2)
        status_layout.addWidget(other, row, 3)
    status_layout.setColumnStretch(1, 1)
    status_layout.setColumnStretch(3, 1)
    layout.addWidget(status_box)

    split = W.QSplitter()
    left = W.QWidget()
    left_layout = W.QVBoxLayout(left)
    left_layout.setContentsMargins(0, 0, 8, 0)
    owner.preview = W.QLabel('等待剧情')
    owner.preview.setAlignment(QtCore.Qt.AlignCenter)
    owner.preview.setWordWrap(True)
    owner.preview.setStyleSheet('font-size:22px;padding:20px')
    left_layout.addWidget(owner.preview, 1)
    owner.preview_note = W.QLabel('日志监听')
    left_layout.addWidget(owner.preview_note)
    split.addWidget(left)
    right = W.QWidget()
    right_layout = W.QVBoxLayout(right)
    right_layout.setContentsMargins(8, 0, 0, 0)
    owner.task = W.QLabel('尚未确认当前任务')
    owner.task.setWordWrap(True)
    owner.task.setStyleSheet('font-size:18px;font-weight:600;')
    owner.task_caption = W.QLabel('当前任务')
    right_layout.addWidget(owner.task_caption)
    right_layout.addWidget(owner.task)
    owner.task_basis = W.QLabel('等待剧情开始事件')
    owner.task_basis.setWordWrap(True)
    right_layout.addWidget(owner.task_basis)
    owner.task_audio = W.QLabel('确认任务后显示可用配音')
    owner.task_audio.setWordWrap(True)
    right_layout.addWidget(owner.task_audio)
    owner.hints = W.QLabel('等待字幕编号')
    owner.hints.setWordWrap(True)
    right_layout.addWidget(owner.hints)
    owner.subtitle = W.QPlainTextEdit()
    owner.subtitle.setReadOnly(True)
    owner.subtitle.setPlaceholderText('实际识别到的当前角色与字幕会显示在这里。')
    owner.subtitle.setMinimumHeight(90)
    right_layout.addWidget(owner.subtitle, 1)
    owner.library = W.QLabel('已有配音：尚未读取')
    owner.library.setWordWrap(True)
    right_layout.addWidget(owner.library)
    owner.counter = W.QLabel('已播放 0 句')
    right_layout.addWidget(owner.counter)
    split.addWidget(right)
    split.setSizes([610, 430])
    layout.addWidget(split, 1)
    owner.details = W.QToolButton()
    owner.details.setText('查看运行记录')
    owner.details.setCheckable(True)
    layout.addWidget(owner.details)
    owner.log = W.QPlainTextEdit()
    owner.log.setReadOnly(True)
    owner.log.setMaximumHeight(100)
    owner.log.setVisible(False)
    owner.details.toggled.connect(owner.log.setVisible)
    layout.addWidget(owner.log)
